export function resolveLanguage(languages: readonly string[]): 'zh-CN' | 'en' {
  return /^zh(?:-|$)/i.test(languages[0] || '') ? 'zh-CN' : 'en';
}

export const locale = resolveLanguage(
  typeof navigator === 'undefined'
    ? []
    : navigator.languages?.length
      ? navigator.languages
      : [navigator.language],
);

export function t(key: keyof typeof english): string {
  return locale === 'zh-CN' ? key : english[key];
}
